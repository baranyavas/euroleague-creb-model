"""Generate the season report and backfill the decision registry.

    python -m src.report

Outputs:
    reports/season_2026_27.md   human-readable results, every game
    data/decision_registry.md   auto block with rounds that were not recorded
"""

from __future__ import annotations

import csv
import statistics
from collections import defaultdict

from . import config

START = "<!-- AUTO-RESULTS:START -->"
END = "<!-- AUTO-RESULTS:END -->"


def load_games() -> list[dict]:
    with (config.DATA_PROC / "games.csv").open(newline="", encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh))
    for r in rows:
        for k in ("creb_total", "team_reb_home", "team_reb_away",
                  "missed_fg_total", "gameday"):
            r[k] = int(r[k])
    return rows


def stats(games: list[dict]) -> dict:
    creb = [g["creb_total"] for g in games]
    miss = [g["missed_fg_total"] for g in games]
    return {
        "games": len(games),
        "mean": statistics.mean(creb),
        "median": statistics.median(creb),
        "sd": statistics.pstdev(creb),
        "miss": statistics.mean(miss),
        "reboppr_t": sum(creb) / sum(miss),
        "p70": 100 * sum(c >= 70 for c in creb) / len(creb),
        "p80": 100 * sum(c >= 80 for c in creb) / len(creb),
        "team_reb": statistics.mean(
            g["team_reb_home"] + g["team_reb_away"] for g in games
        ),
    }


def write_season_report(games: list[dict]) -> None:
    base = [g for g in games if g["season"] == config.BASE_SEASON]
    live = [g for g in games if g["season"] == config.LIVE_SEASON]
    live.sort(key=lambda g: (g["date"], g["gamecode"]))
    sb, sl = stats(base), stats(live)

    lines = [
        "# 2026-27 c-reb season report",
        "",
        "_Generated by `python -m src.report`. Settlement: "
        "c-reb = total-row T - team-row T (team rebounds excluded)._",
        "",
        "## Season comparison",
        "",
        "| metric | 2025-26 (380) | 2026-27 to date |",
        "|---|---:|---:|",
        f"| games | {sb['games']} | {sl['games']} |",
        f"| mean c-reb | {sb['mean']:.2f} | {sl['mean']:.2f} |",
        f"| median c-reb | {sb['median']:.0f} | {sl['median']:.0f} |",
        f"| sd c-reb | {sb['sd']:.2f} | {sl['sd']:.2f} |",
        f"| mean missed FG | {sb['miss']:.2f} | {sl['miss']:.2f} |",
        f"| reboppr-t (c-reb / missed FG) | {sb['reboppr_t']:.3f} | {sl['reboppr_t']:.3f} |",
        f"| 70+ share | {sb['p70']:.1f}% | {sl['p70']:.1f}% |",
        f"| 80+ share | {sb['p80']:.1f}% | {sl['p80']:.1f}% |",
        f"| team rebounds per game (context) | {sb['team_reb']:.2f} | {sl['team_reb']:.2f} |",
        "",
        "The realization rate is the number that matters: c-reb is "
        f"{sl['reboppr_t'] * 100:.1f}% of missed field goals in 2026-27, "
        "so a forecast that assigns every miss to a player is biased high by "
        "the team-rebound bucket.",
        "",
        "## Every game",
        "",
        "`team reb` is home+away team rebounds (excluded from c-reb). "
        "`miss FG` is both teams' (FGA-FGM).",
        "",
        "| date | rnd | home-away | score | c-reb | team reb | miss FG | reboppr-t |",
        "|---|---:|---|---|---:|---:|---:|---:|",
    ]
    for g in live:
        r = f"{float(g['reboppr_t']):.3f}" if g["reboppr_t"] else "nr"
        lines.append(
            f"| {g['date']} | {g['gameday']} | {g['home_id']}-{g['away_id']} "
            f"| {g['home_score']}-{g['away_score']} | {g['creb_total']} "
            f"| {g['team_reb_home'] + g['team_reb_away']} | {g['missed_fg_total']} | {r} |"
        )

    lines += [
        "",
        "## Recorded decisions vs outcomes",
        "",
        "Only the W2-W4 rounds were forecast while the model was live. "
        "`gap = forecast - line`; negative gap means the model was below the market.",
        "",
        "| date | teams | forecast | line | gap | actual | result | call |",
        "|---|---|---:|---:|---:|---:|---|---|",
    ]

    decisions = _decisions()
    residuals = []
    band = defaultdict(lambda: [0, 0])
    for d in decisions:
        game = _find(live, d)
        if game is None:
            continue
        actual = game["creb_total"]
        line = d["line"]
        result = "under" if actual < line else "over" if actual > line else "push"
        if d["forecast"] is not None:
            gap = d["forecast"] - line
            call = "under" if gap < 0 else "over"
            ok = "yes" if call == result else "no"
            residuals.append(actual - d["forecast"])
            fc = f"{d['forecast']:.1f}"
            gap_txt = f"{gap:+.1f}"
        else:
            fc, gap_txt, call, ok = "nr", "nr", "nr", "nr"
        band[result][0] += 1
        band[result][1] += 1
        lines.append(
            f"| {d['date']} | {d['team_a']}-{d['team_b']} | {fc} | "
            f"{line:.1f} | {gap_txt} | {actual} | {result} | {ok} |"
        )

    n_under, n_over = band["under"][0], band["over"][0]
    lines += [
        "",
        f"**Direction record vs recorded lines: {n_under} under / {n_over} over.**",
    ]

    diffs = []
    for d in decisions:
        game = _find(live, d)
        if game is None or not d.get("actual_recorded"):
            continue
        if int(d["actual_recorded"]) != game["creb_total"]:
            diffs.append(
                f"{d['team_a']}-{d['team_b']} {game['creb_total']} vs {d['actual_recorded']}"
            )
    if diffs:
        lines += [
            "",
            f"**Settlement check:** {len(decisions) - len(diffs)}/{len(decisions)} "
            "recorded games reproduce exactly from the API box score. "
            "Differing by 1 rebound: " + "; ".join(diffs) + ". "
            "The API figure (total-row T - team-row T) is treated as authoritative; "
            "the live entry was a same-day box score that was later revised.",
        ]

    if residuals:
        lines += [
            "",
            f"**Residuals on the {len(residuals)} recorded forecasts: "
            f"mean {statistics.mean(residuals):+.2f}, "
            f"MAE {statistics.mean(abs(r) for r in residuals):.2f}.**",
            "Positive residual = the model was too low.",
        ]

    (config.REPORTS / "season_2026_27.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote reports/season_2026_27.md ({len(live)} games)")


def _decisions() -> list[dict]:
    path = config.ROOT / "data" / "decisions_2026_27.csv"
    with path.open(newline="", encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh))
    for r in rows:
        r["forecast"] = float(r["forecast"]) if r["forecast"] else None
        r["line"] = float(r["line"])
    return rows


def _find(games: list[dict], d: dict):
    for g in games:
        if g["date"] == d["date"] and {g["home_id"], g["away_id"]} == {d["team_a"], d["team_b"]}:
            return g
    return None


def write_registry_block(games: list[dict]) -> None:
    live = [g for g in games if g["season"] == config.LIVE_SEASON]
    recorded = {
        (d["date"], frozenset((d["team_a"], d["team_b"])))
        for d in _decisions()
    }
    missing = [
        g for g in live
        if (g["date"], frozenset((g["home_id"], g["away_id"]))) not in recorded
    ]
    missing.sort(key=lambda g: (g["date"], g["gamecode"]))

    lines = [
        START,
        "",
        "## results backfill — rounds without a recorded forecast",
        "",
        "_Auto-generated by `python -m src.report`. Do not hand-edit inside the markers._",
        "",
        "The model was offline from 2026-10-09 to 2026-11-17. Forecasts for these",
        "games were never locked pregame, so per experiment rule 8 they stay `nr`.",
        "Only settled c-reb (total-row T - team-row T), team-rebound context and",
        "post-game diagnostics are filled in. Nothing here is a decision record.",
        "",
        "| date | rnd | home-away | actual c-reb | team reb | missed fg | reboppr-t | result |",
        "|---|---:|---|---:|---:|---:|---:|---|",
    ]
    for g in missing:
        r = f"{float(g['reboppr_t']):.3f}" if g["reboppr_t"] else "nr"
        lines.append(
            f"| {g['date']} | {g['gameday']} | {g['home_id']}-{g['away_id']} "
            f"| {g['creb_total']} | {g['team_reb_home'] + g['team_reb_away']} "
            f"| {g['missed_fg_total']} | {r} | nr |"
        )
    lines += [
        "",
        f"_{len(missing)} games backfilled. Live forecasting resumes with "
        "`python -m src.forecast`._",
        "",
        END,
    ]
    block = "\n".join(lines)

    path = config.ROOT / "data" / "decision_registry.md"
    text = path.read_text(encoding="utf-8")
    if START in text:
        head, rest = text.split(START, 1)
        tail = rest.split(END, 1)[1] if END in rest else ""
        text = head + block + tail
    else:
        text = text.rstrip() + "\n\n" + block + "\n"
    path.write_text(text, encoding="utf-8")
    print(f"updated data/decision_registry.md ({len(missing)} backfilled games)")


def main() -> None:
    games = load_games()
    write_season_report(games)
    write_registry_block(games)


if __name__ == "__main__":
    main()
