"""Rewrite STATE.md from the data. Do not hand-edit STATE.md.

    python -m src.state
"""

from __future__ import annotations

import csv
import statistics

from . import config


def _rows(path):
    with path.open(newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def season_line(games: list[dict]) -> str:
    creb = [int(g["creb_total"]) for g in games]
    miss = [int(g["missed_fg_total"]) for g in games]
    return (
        f"{len(games)} games, mean {statistics.mean(creb):.2f}, "
        f"median {statistics.median(creb):.0f}, sd {statistics.pstdev(creb):.2f}, "
        f"mean missed FG {statistics.mean(miss):.2f}, "
        f"reboppr-t {sum(creb) / sum(miss):.3f}"
    )


def main() -> None:
    games = _rows(config.DATA_PROC / "games.csv")
    base = [g for g in games if g["season"] == config.BASE_SEASON]
    live = sorted(
        (g for g in games if g["season"] == config.LIVE_SEASON),
        key=lambda g: (g["date"], g["gamecode"]),
    )
    last = live[-1] if live else None

    decisions = _rows(config.ROOT / "data" / "decisions_2026_27.csv")
    under = sum(1 for d in decisions if d["result_recorded"] == "under")
    over = sum(1 for d in decisions if d["result_recorded"] == "over")
    fc = [d for d in decisions if d["forecast"]]
    resid = [float(d["actual_recorded"]) - float(d["forecast"]) for d in fc]

    bt_path = config.REPORTS / "backtest_2026_27.csv"
    bt = _rows(bt_path) if bt_path.exists() else []
    bt_line = "not run"
    if bt:
        r = [float(x["residual"]) for x in bt]
        bt_line = (
            f"{len(bt)} games, MAE {statistics.mean(abs(v) for v in r):.2f}, "
            f"bias {statistics.mean(r):+.2f}, RMSE "
            f"{(sum(v * v for v in r) / len(r)) ** 0.5:.2f}"
        )

    lines = [
        "# Project state",
        "",
        "_Generated by `python -m src.state` — do not hand-edit._",
        "",
        "## Resume prompt (paste after a compaction)",
        "",
        "```",
        "Read STATE.md, then reports/season_2026_27.md. Continue the EuroLeague",
        "c-reb model. Rules and settlement are on disk. Refresh with:",
        "python -m src.update",
        "Forecast a matchup with: ./.venv/bin/python -m src.forecast HOME AWAY --line X",
        "```",
        "",
        "## If you are a new session, read in this order",
        "",
        "1. This file.",
        "2. `reports/season_2026_27.md` — every 2026-27 game and the recorded decisions.",
        "3. `data/decision_registry.md` — the chronological decision ledger.",
        "4. `README.md` — model, findings, limitations.",
        "",
        "## What we are doing",
        "",
        "Pricing EuroLeague **credited rebounds (c-reb)**: player-credited O+D only.",
        "Team rebounds are excluded from the target and kept as context.",
        "",
        "**Settlement rule (unchanged):** c-reb = total-row T − team-row T.",
        "Do not add the bottom-row O+D: those include the team-rebound bucket.",
        "",
        "## Findings (do not re-derive)",
        "",
        "- Missed field goals are the opportunity engine. 2025-26 correlation",
        "  c-reb vs missed FG is 0.907; the single-variable OLS is",
        "  c-reb = 3.126 + 0.8719 × missed FG (r² 0.823). The rebuilt dataset",
        "  reproduces both, which is the parser's regression test.",
        "- Realization is not 1:1. c-reb / missed FG is 0.918 in 2025-26 and",
        "  0.917 in 2026-27 to date. The missing ~8% is the team-rebound bucket.",
        "  A forecast that sends every miss to a player is biased high by ~6.",
        "- Team rebounds (~7.4-7.8 per game) are stochastic from a pregame view;",
        "  keep them as context, never inside the target.",
        "- The market has sat above realised c-reb: recorded W2-W4 lines averaged",
        "  ~70 against ~65 realised. Under was 22/27. Small sample, not a law.",
        "",
        "## Operating rules",
        "",
        "- **Target:** player-credited rebounds only. c-reb = total-row T − team-row T.",
        "- **Model:** v0.7 two-stage (misses × player-only rebound rates) plus the",
        "  v0.8 shrunk residual correction. No new model, no extra features.",
        "- **Player-only mode:** `base_forecast(..., player_only=True)` keeps",
        "  ORB+DRB at the settled level. The legacy blend forces ORB+DRB = 1.0",
        "  and silently re-adds team rebounds, so it is not used for pricing.",
        "- **Line:** never enters the forecast. `gap = forecast − line` only.",
        "- **Missing forecasts stay `nr`.** Never reconstruct a pregame forecast",
        "  after the game (experiment rule 2 and 8).",
        "- **Backtests are retrospective.** They are diagnostics and are never",
        "  written into the decision registry.",
        "- **Model changes:** only with out-of-sample evidence, documented in",
        "  `data/model_notes.md`.",
        "",
        "## Snapshot",
        "",
        f"- 2025-26 baseline: {season_line(base)}.",
        f"- 2026-27 to date: {season_line(live)}.",
    ]
    if last:
        lines.append(
            f"- Last game in the dataset: {last['date']} (round {last['gameday']}), "
            f"{last['home_id']}-{last['away_id']} {last['creb_total']} c-reb."
        )
    lines += [
        f"- Recorded decisions: {len(decisions)} games, {under} under / {over} over "
        "against the decision lines.",
        f"- Recorded-forecast residuals ({len(fc)}): "
        f"mean {statistics.mean(resid):+.2f}, MAE "
        f"{statistics.mean(abs(v) for v in resid):.2f}." if fc else
        "- Recorded-forecast residuals: none.",
        f"- Retrospective backtest of the live pipeline: {bt_line}.",
        "",
        "## Coverage gap",
        "",
        "- The model was offline 2026-10-09 → 2026-11-17.",
        "- Rounds 1 and 5-11 have results but **no recorded pregame forecast**.",
        "  They are backfilled in `data/decision_registry.md` as `nr` and are",
        "  excluded from every accuracy claim.",
        "",
        "## Daily routine",
        "",
        "```",
        "python -m src.update                                  # fetch, build, validate, report, state",
        "./.venv/bin/python -m src.forecast BAR BJK --line 71.5   # price a matchup",
        "./.venv/bin/python -m src.forecast --backtest            # retrospective check",
        "```",
        "",
        "Ingest is stdlib-only. The forecast imports `model/`, which needs numpy",
        "and pandas (`.venv`).",
        "",
        "## File map",
        "",
        "| file | what it holds |",
        "|---|---|",
        "| `STATE.md` | this handoff summary |",
        "| `LOG.md` | one line per work session |",
        "| `data/decision_registry.md` | decision ledger + auto results backfill |",
        "| `data/decisions_2026_27.csv` | the recorded forecasts and lines, machine-readable |",
        "| `data/processed/games.csv` | one row per game |",
        "| `data/processed/team_games.csv` | one row per team-game |",
        "| `reports/season_2026_27.md` | season report, every game |",
        "| `reports/backtest_2026_27.md` | retrospective model check |",
        "| `src/build.py` | XML → CSV |",
        "| `src/validate.py` | reproduces the published 2025-26 baseline |",
        "| `src/forecast.py` | v0.7 + v0.8 pricing and backtest |",
        "| `src/report.py` | season report + registry backfill |",
        "| `src/state.py` | this file |",
        "",
        "## Reading budget",
        "",
        "- `STATE.md` is capped and cheap.",
        "- `reports/season_2026_27.md` ~110 table rows: read the top and the",
        "  recorded-decisions block, not the whole game list, unless needed.",
        "- Never load `data/raw/` (24 MB of XML). `data/processed/` is small.",
        "",
        "## Open threads",
        "",
        "- Resume live forecasts when the provider posts round-12 lines. The",
        "  first decision after the gap should be logged with its timestamp.",
        "- The 2026-27 sample is 110 games. Do not change weights on it.",
        "- Line-gap tracking: the market's under bias held through W4 (22/27).",
        "  Re-test it on the next recorded slate before trusting it.",
        "- Reboppr-o / reboppr-d are now player-only. The old registry notes",
        "  quoted team-inclusive splits; do not mix the two scales.",
        "",
    ]

    (config.ROOT / "STATE.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote STATE.md")


if __name__ == "__main__":
    main()
