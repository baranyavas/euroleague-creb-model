        "| `src/bets.py` | ticket-by-ticket P&L printout |",
        "| `src/bankroll.py` | P&L aggregates + report writer |",
        "| `src/nights.py` | 4-leg-night calendar from the official schedule |",
        "| `src/report.py` | season report + registry backfill |",
